def set_language(lang: str) -> str:
    """Fija el idioma activo; devuelve el efectivo (o el default si no existe)."""
    global _current
    _current = lang if lang in AVAILABLE_LANGUAGES else DEFAULT_LANGUAGE
    return _current


def get_language() -> str:
    return _current


def available_languages() -> tuple:
    return AVAILABLE_LANGUAGES


def t(key: str, **kwargs) -> str:
    """Traduce una clave; devuelve la clave misma si falta en ambos idiomas."""
    template = STRINGS.get(_current, {}).get(key) or STRINGS[DEFAULT_LANGUAGE].get(key)
    if template is None:
        return key
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError):
            return template
    return template
